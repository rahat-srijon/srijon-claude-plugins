// @ts-check
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { log } from './log.js';
import { readJsonObject, writeJsonAtomic } from './state.js';

/**
 * The `statusLine` object in Claude Code settings.
 * @typedef {Record<string, unknown> & { command?: string }} StatusLine
 */

/**
 * What setup changed, kept so teardown can undo it.
 * @typedef {object} SetupRecord
 * @property {string} settingsFile
 * @property {StatusLine | null} previous The status line before setup, or null if there was none.
 * @property {string} command The status line command setup installed.
 * @property {string} installedAt ISO time.
 */

/**
 * @typedef {object} SetupPlan
 * @property {'ready' | 'installed'} status 'installed' when setup already ran.
 * @property {string} settingsFile
 * @property {StatusLine | null} previous
 * @property {StatusLine} next
 * @property {string} shimFile
 * @property {string} backupFile
 * @property {string[]} warnings
 */

/**
 * @typedef {object} TeardownResult
 * @property {'restored' | 'changed' | 'not-installed'} status 'changed' when the status line no
 *   longer used the shim, so settings were left alone.
 * @property {string} settingsFile
 * @property {StatusLine | null} restored The status line now in settings, when restored.
 */

const SHIM_NAME = 'statusline.mjs';
const RECORD_NAME = 'setup.json';
const BACKUP_NAME = 'settings.backup.json';
/** Makes the shim pass its input on to the previous status line command. */
const TEE_FLAG = '--tee';

/**
 * The directory holding usage-limit files.
 * @param {string} dataDir
 * @returns {string}
 */
export function usageDir(dataDir) {
  return path.join(dataDir, 'usage');
}

/**
 * @param {string} dataDir
 * @returns {string}
 */
export function shimFile(dataDir) {
  return path.join(usageDir(dataDir), SHIM_NAME);
}

/**
 * @param {string} dataDir
 * @returns {string}
 */
export function setupRecordFile(dataDir) {
  return path.join(usageDir(dataDir), RECORD_NAME);
}

/**
 * The user settings file Claude Code reads the status line from.
 * @returns {string}
 */
export function userSettingsFile() {
  const configDir = process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude');
  return path.join(configDir, 'settings.json');
}

/**
 * Source of the shim that Claude Code runs as the status line. It is
 * self-contained apart from the import of the plugin's usage module, so the
 * status line keeps working when the plugin moves or is removed.
 * @param {string} pluginRoot
 * @param {string} dataDir
 * @returns {string}
 */
export function shimSource(pluginRoot, dataDir) {
  return `// Generated by claudio-notify for usage-limit sounds. Every session start
// rewrites this file, so edits are lost. Remove it with /claudio-notify:teardown-usage.
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const PLUGIN_ROOT = ${JSON.stringify(pluginRoot)};
const DATA_DIR = ${JSON.stringify(dataDir)};
const STDIN_TIMEOUT_MS = 3000;

// With ${TEE_FLAG}, stdin is copied to stdout for the previous status line command.
const tee = process.argv.includes('${TEE_FLAG}');
const chunks = [];
let finished = false;

async function finish() {
  if (finished) {
    return;
  }
  finished = true;
  clearTimeout(timer);
  process.stdin.destroy();
  const input = Buffer.concat(chunks);
  if (tee) {
    // Windows PowerShell 5.1 pipes text between programs as ASCII, so non-ASCII
    // characters are passed on as JSON escapes, which parse to the same value.
    process.stdout.write(process.platform === 'win32'
      ? input.toString('utf8').replace(/[\\u0080-\\uffff]/g, (c) => \`\\\\u\${c.charCodeAt(0).toString(16).padStart(4, '0')}\`)
      : input);
  }
  try {
    process.env.CLAUDIO_DATA_DIR = DATA_DIR;
    process.env.CLAUDE_PLUGIN_ROOT = PLUGIN_ROOT;
    const usage = await import(pathToFileURL(path.join(PLUGIN_ROOT, 'scripts', 'usage.js')).href);
    await usage.onStatusLine(input.toString('utf8'), { dataDir: DATA_DIR, pluginRoot: PLUGIN_ROOT });
  } catch {
    // The status line must keep working even if the plugin is gone.
  }
}

const timer = setTimeout(finish, STDIN_TIMEOUT_MS);
process.stdout.on('error', () => {});
process.stdin.on('data', (chunk) => chunks.push(chunk));
process.stdin.once('end', finish);
process.stdin.once('error', finish);
`;
}

/**
 * Write the shim if its content changed.
 * @param {string} dataDir
 * @param {string} pluginRoot
 * @returns {boolean} True if the file was written.
 */
export function writeShim(dataDir, pluginRoot) {
  const file = shimFile(dataDir);
  const source = shimSource(pluginRoot, dataDir);
  try {
    if (fs.readFileSync(file, 'utf8') === source) {
      return false;
    }
  } catch {
    // Missing: write it.
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, source);
  fs.renameSync(tmp, file);
  return true;
}

/**
 * Point the shim at the current plugin root when setup has run. Plugin
 * updates change the root, so SessionStart calls this. Never throws.
 * @param {{ dataDir: string, pluginRoot: string }} roots
 * @returns {boolean} True if the shim was rewritten.
 */
export function refreshShim({ dataDir, pluginRoot }) {
  try {
    if (!fs.existsSync(setupRecordFile(dataDir))) {
      return false;
    }
    const written = writeShim(dataDir, pluginRoot);
    if (written) {
      log('info', `usage: status line shim now points at ${pluginRoot}`);
    }
    return written;
  } catch (err) {
    log('warn', 'usage: cannot refresh the status line shim', err);
    return false;
  }
}

/**
 * The status line command that runs the shim, piping into the previous
 * command when there was one. The pipe lets Claude Code's own shell run the
 * previous command exactly as before.
 * @param {string} dataDir
 * @param {string | undefined} previousCommand
 * @returns {string}
 */
export function shimCommand(dataDir, previousCommand) {
  // Forward slashes, because Git Bash on Windows drops unquoted backslashes.
  const shim = `node "${shimFile(dataDir).replace(/\\/g, '/')}"`;
  return previousCommand?.trim() ? `${shim} ${TEE_FLAG} | ${previousCommand.trim()}` : shim;
}

/**
 * Work out what setup would change, without changing anything.
 * @param {{ dataDir: string, settingsFile?: string, projectDir?: string }} options
 * @returns {SetupPlan}
 * @throws {Error} When the settings file cannot be read or parsed.
 */
export function planSetup({ dataDir, settingsFile = userSettingsFile(), projectDir }) {
  const settings = readSettings(settingsFile);
  const current = asStatusLine(settings.statusLine);
  const record = readSetupRecord(dataDir);
  const installed = record !== null && current?.command === record.command;
  /** @type {string[]} */
  const warnings = [];
  /** @type {StatusLine | null} */
  let previous = installed ? record.previous : current;
  if (!installed && referencesShim(previous?.command, dataDir)) {
    // The setup record is gone, so recover the chained command from the shim's own.
    const separator = ` ${TEE_FLAG} | `;
    const chained = String(previous?.command).split(separator).slice(1).join(separator);
    previous = chained ? { ...previous, command: chained } : null;
    warnings.push('The status line already ran the claudio-notify shim without a setup record; setting it up again.');
  }
  const command = shimCommand(dataDir, previous?.command);
  for (const file of projectSettingsFiles(projectDir)) {
    if (readSettingsOrNull(file)?.statusLine !== undefined) {
      warnings.push(`${file} sets its own status line, which overrides yours in that project.`);
    }
  }
  return {
    status: installed ? 'installed' : 'ready',
    settingsFile,
    previous,
    next: { ...(previous ?? {}), type: 'command', command },
    shimFile: shimFile(dataDir),
    backupFile: path.join(usageDir(dataDir), BACKUP_NAME),
    warnings,
  };
}

/**
 * Apply a setup plan: write the shim, back up the settings file, point the
 * status line at the shim and keep a record for teardown.
 * @param {SetupPlan} plan
 * @param {{ dataDir: string, pluginRoot: string }} roots
 * @returns {void}
 * @throws {Error} On IO errors.
 */
export function applySetup(plan, { dataDir, pluginRoot }) {
  writeShim(dataDir, pluginRoot);
  if (plan.status === 'installed') {
    return;
  }
  const settings = readSettings(plan.settingsFile);
  if (fs.existsSync(plan.settingsFile)) {
    fs.copyFileSync(plan.settingsFile, plan.backupFile);
  }
  settings.statusLine = plan.next;
  writeSettings(plan.settingsFile, settings);
  /** @type {SetupRecord} */
  const record = {
    settingsFile: plan.settingsFile,
    previous: plan.previous,
    command: /** @type {string} */ (plan.next.command),
    installedAt: new Date().toISOString(),
  };
  writeJsonAtomic(setupRecordFile(dataDir), record);
  log('info', `usage: status line set to ${record.command}`);
}

/**
 * Undo setup: restore the previous status line if the shim is still in use,
 * then remove the shim and the setup record.
 * @param {{ dataDir: string, settingsFile?: string }} options
 * @returns {TeardownResult}
 * @throws {Error} On IO errors or an unreadable settings file.
 */
export function teardown({ dataDir, settingsFile }) {
  const record = readSetupRecord(dataDir);
  const file = settingsFile ?? record?.settingsFile ?? userSettingsFile();
  if (!record) {
    return { status: 'not-installed', settingsFile: file, restored: null };
  }
  const settings = readSettings(file);
  const current = asStatusLine(settings.statusLine);
  const usesShim = current?.command === record.command || referencesShim(current?.command, dataDir);

  /** @type {TeardownResult} */
  let result;
  if (usesShim) {
    if (record.previous) {
      settings.statusLine = record.previous;
    } else {
      delete settings.statusLine;
    }
    writeSettings(file, settings);
    result = { status: 'restored', settingsFile: file, restored: record.previous };
  } else {
    result = { status: 'changed', settingsFile: file, restored: null };
  }
  fs.rmSync(setupRecordFile(dataDir), { force: true });
  fs.rmSync(shimFile(dataDir), { force: true });
  log('info', `usage: teardown ${result.status}`);
  return result;
}

/**
 * @param {string} dataDir
 * @returns {SetupRecord | null}
 */
export function readSetupRecord(dataDir) {
  const raw = readJsonObject(setupRecordFile(dataDir));
  if (!raw || typeof raw.command !== 'string' || typeof raw.settingsFile !== 'string') {
    return null;
  }
  return {
    settingsFile: raw.settingsFile,
    previous: asStatusLine(raw.previous),
    command: raw.command,
    installedAt: typeof raw.installedAt === 'string' ? raw.installedAt : '',
  };
}

/**
 * @param {unknown} command
 * @param {string} dataDir
 * @returns {boolean}
 */
function referencesShim(command, dataDir) {
  return typeof command === 'string' && command.includes(shimFile(dataDir).replace(/\\/g, '/'));
}

/**
 * @param {string | undefined} projectDir
 * @returns {string[]}
 */
function projectSettingsFiles(projectDir) {
  if (!projectDir) {
    return [];
  }
  return ['settings.json', 'settings.local.json'].map((name) => path.join(projectDir, '.claude', name));
}

/**
 * @param {unknown} value
 * @returns {StatusLine | null}
 */
function asStatusLine(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? /** @type {StatusLine} */ (value)
    : null;
}

/**
 * Read a settings file; a missing file reads as empty.
 * @param {string} file
 * @returns {Record<string, unknown>}
 * @throws {Error} When the file exists but is not a JSON object.
 */
function readSettings(file) {
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if (/** @type {NodeJS.ErrnoException} */ (err).code === 'ENOENT') {
      return {};
    }
    throw err;
  }
  let data;
  try {
    data = JSON.parse(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text);
  } catch (err) {
    throw new Error(`${file} is not valid JSON (${err instanceof Error ? err.message : String(err)}); fix it first`);
  }
  if (data === null || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error(`${file} must contain a JSON object`);
  }
  return data;
}

/**
 * @param {string} file
 * @returns {Record<string, unknown> | null}
 */
function readSettingsOrNull(file) {
  try {
    return readSettings(file);
  } catch {
    return null;
  }
}

/**
 * Write settings atomically with two-space indentation, as Claude Code does.
 * @param {string} file
 * @param {Record<string, unknown>} settings
 * @returns {void}
 */
function writeSettings(file, settings) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.claudio-${process.pid}.tmp`;
  try {
    fs.writeFileSync(tmp, `${JSON.stringify(settings, null, 2)}\n`);
    fs.renameSync(tmp, file);
  } catch (err) {
    fs.rmSync(tmp, { force: true });
    throw err;
  }
}
